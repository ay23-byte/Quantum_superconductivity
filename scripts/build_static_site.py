"""Build a self-contained static dashboard in dist/ for static hosting."""

from __future__ import annotations

import shutil
from pathlib import Path

from build_dashboard_data import main as build_dashboard_data


ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
STAGING = ROOT / ".dist-staging"
FRONTEND_FILES = (
    "app.js",
    "convergence.js",
    "convergence_data.js",
    "dashboard_runs.js",
    "data.js",
    "index.html",
    "phase_size.js",
    "phase_size_data.js",
    "research.css",
    "research.html",
    "research.js",
    "research_runs.js",
    "research_data.js",
    "styles.css",
)
DATA_RUNS = (
    "quick_20261023",
    "research_20261023",
    "user_simulation_20261023",
    "research_hartree_20261023",
    "research_hartree_pilot_20261023",
    "research_hartree_robust_20261023",
    "convergence_hartree_20sample_20261023",
    "convergence_hartree_multipoint_20261026",
    "qmc_benchmark_scalettar_20261026",
    "virtual_sts_20261026",
    "phase_size_validation_20261023",
)
DASHBOARD_FIGURE_RUNS = (
    "quick_20261023",
    "research_20261023",
    "user_simulation_20261023",
    "convergence_hartree_multipoint_20261026",
    "virtual_sts_20261026",
)


def copy_required(source: Path, destination: Path) -> None:
    if not source.exists():
        raise FileNotFoundError(f"Required deployment input is missing: {source}")
    if source.is_dir():
        shutil.copytree(source, destination)
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)


def main() -> None:
    build_dashboard_data()
    # Only replace the known build output inside this project. Use a staging
    # directory so a failed copy does not leave a partially built site.
    if DIST.parent.resolve() != ROOT.resolve() or STAGING.parent.resolve() != ROOT.resolve():
        raise RuntimeError("Deployment output paths must remain inside the project root")
    for path in (DIST, STAGING):
        if path.exists() and not (path / ".quantum-static-site").is_file():
            raise RuntimeError(f"Refusing to replace unmarked directory: {path}")
    if STAGING.exists():
        shutil.rmtree(STAGING)
    STAGING.mkdir()
    (STAGING / ".quantum-static-site").write_text("Generated by scripts/build_static_site.py\n", encoding="utf-8")

    try:
        for name in FRONTEND_FILES:
            copy_required(ROOT / "frontend" / name, STAGING / name)

        copy_required(ROOT / "README.md", STAGING / "README.md")
        copy_required(ROOT / "docs", STAGING / "docs")
        for run_id in DASHBOARD_FIGURE_RUNS:
            copy_required(ROOT / "results" / "figures" / run_id, STAGING / "results" / "figures" / run_id)
        for run_id in DATA_RUNS:
            copy_required(ROOT / "results" / "data" / run_id, STAGING / "results" / "data" / run_id)

        # Pages are served from the site root, so translate source-tree links
        # into paths that also work beneath a project subpath (for example
        # GitHub Pages at /repository/).
        for name in ("index.html", "research.html"):
            path = STAGING / name
            contents = path.read_text(encoding="utf-8")
            contents = contents.replace("../README.md", "README.md")
            contents = contents.replace("../docs/", "docs/")
            contents = contents.replace("../results/", "results/")
            path.write_text(contents, encoding="utf-8")
        for name in ("app.js", "convergence.js", "phase_size.js"):
            path = STAGING / name
            contents = path.read_text(encoding="utf-8")
            contents = contents.replace("../results/", "results/")
            path.write_text(contents, encoding="utf-8")

        (STAGING / "DEPLOY.md").write_text(
            "# Static deployment\n\n"
            "This folder is a prebuilt static site. Publish the contents of this directory "
            "with any static hosting provider. The home dashboard is `index.html`; the "
            "fixed-density research dashboard is `research.html`. No Python runtime is "
            "needed to serve the deployed site. Rebuild from the project root with "
            "`python scripts/build_static_site.py`.\n",
            encoding="utf-8",
        )

        if DIST.exists():
            shutil.rmtree(DIST)
        STAGING.rename(DIST)
    except Exception:
        if STAGING.exists():
            shutil.rmtree(STAGING)
        raise

    files = sum(1 for item in DIST.rglob("*") if item.is_file())
    print(f"Built static site: {DIST} ({files} files)")


if __name__ == "__main__":
    main()
